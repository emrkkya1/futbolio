import java.awt.Font;
import java.awt.font.FontRenderContext;
import java.awt.geom.PathIterator;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;

/** Run from the repository root: java scripts/branding/GenerateReadmeLogo.java */
class GenerateReadmeLogo {
    public static void main(String[] args) throws Exception {
        var font = Font.createFont(Font.TRUETYPE_FONT,
            Path.of("android/src/main/res/font/kodchasan.ttf").toFile()).deriveFont(64f);
        var outline = font.createGlyphVector(new FontRenderContext(null, true, true), "Futbolio").getOutline(144, 84);
        var iterator = outline.getPathIterator(null);
        var coordinates = new double[6];
        var data = new StringBuilder();
        while (!iterator.isDone()) {
            int type = iterator.currentSegment(coordinates);
            data.append("MLQCZ".charAt(type));
            int count = switch (type) { case 0, 1 -> 2; case 2 -> 4; case 3 -> 6; default -> 0; };
            for (int i = 0; i < count; i++) {
                if (i > 0) data.append(' ');
                data.append(String.format(Locale.ROOT, "%.3f", coordinates[i]));
            }
            iterator.next();
        }
        int width = (int) Math.ceil(outline.getBounds2D().getMaxX()) + 24;
        var svg = """
            <svg xmlns="http://www.w3.org/2000/svg" width="%d" height="128" viewBox="0 0 %d 128" role="img" aria-labelledby="title desc">
              <title id="title">Futbolio</title>
              <desc id="desc">Solid green diamond F mark and Kodchasan wordmark, matching the Android and desktop apps.</desc>
              <!-- Generated by scripts/branding/GenerateReadmeLogo.java from the bundled Kodchasan font. Outlines need no installed or remote fonts. -->
              <path fill="#3a8638" fill-rule="evenodd" d="M21 0 42 21 21 42 0 21ZM13 10h16v6H19v4h8v6h-8v6h-6Z" transform="translate(36 22) scale(2)"/>
              <path fill="#3a8638" d="%s"/>
            </svg>
            """.formatted(width, width, data);
        Files.writeString(Path.of("docs/assets/futbolio-logo.svg"), svg);
    }
}
